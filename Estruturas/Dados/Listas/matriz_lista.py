# Uma matriz 3x3

matriz = [[1, 2, 3], [4, 5, 6], [7, 8, 9]]

# Acessando o numero 6 (linha indica 1, coluna indice 2)

numero = matriz[1][2]

print(f"\nNúmero acessado: {numero}")

