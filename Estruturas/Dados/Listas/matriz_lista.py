# Uma matriz 3x3 com numero e string

matriz2 = [[1, 2, 3], ["a", "b", "c"], [7, 8, 9]]

print(f"\nMatriz 3x3 com números e strings: {matriz2}")

print("\nAcessando a letra 'b' (linha indice 1, coluna indice 1)")

letra = matriz2[1][1]
print(f"\nLetra acessada: {letra}")