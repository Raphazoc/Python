def somar (a, b):
    return a + b

print(somar(5, 3))

def subtrair (a, b):
    return a - b

print(subtrair(5, 3))

def multiplicar (a, b):
    return a * b

print(multiplicar(5, 3))

def dividir (a, b):
    return a // b

print(dividir(6, 3))

# Funções também podem receber argumentos para realizar operações matemáticas. No exemplo acima, temos quatro funções que realizam operações matemáticas básicas: soma, subtração, multiplicação e divisão. Cada função recebe dois argumentos (a e b) e retorna o resultado da operação correspondente. As funções são chamadas com valores específicos e os resultados são exibidos no terminal usando o comando print().