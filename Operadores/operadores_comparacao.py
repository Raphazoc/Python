# Operadores de Comparação em Python

saldo = 200
saque = 200

# Igualdade (==)
print(saldo == saque)  # True

# Diferença (!=)
print(saldo != saque)  # False

# Maior que (>)
print(saldo > saque)   # False

# Maior ou igual (>=)
print(saldo >= saque)  # True

# Menor que (<)
print(saldo < saque)   # False

# Menor ou igual (<=)
print(saldo <= saque)  # True
